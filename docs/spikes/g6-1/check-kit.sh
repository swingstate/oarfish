#!/bin/sh
# Local checks of the G6.1 spike kit, run on the development machine (not on the Pi).
# Throwaway, like everything in this directory. Needs: sh, awk, sed, grep, go; uses
# dash, bash and shellcheck when they are installed (and says so when not).
set -u
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../../.." && pwd)
fails=0
ok()   { printf 'ok    %s\n' "$*"; }
bad()  { printf 'FAIL  %s\n' "$*"; fails=$((fails + 1)); }
skip() { printf 'skip  %s\n' "$*"; }
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# 1. shell syntax and shellcheck
for f in spike.sh build-probe.sh check-kit.sh; do
  if sh -n "$here/$f"; then ok "sh -n $f"; else bad "sh -n $f"; fi
  if command -v dash >/dev/null 2>&1; then
    if dash -n "$here/$f"; then ok "dash -n $f"; else bad "dash -n $f"; fi
  else skip "dash not installed"; fi
done
if command -v shellcheck >/dev/null 2>&1; then
  if shellcheck -s sh "$here/spike.sh" "$here/build-probe.sh" "$here/check-kit.sh"; then ok "shellcheck -s sh (all severities)"; else bad "shellcheck"; fi
else skip "shellcheck is not installed"; fi

# 2. the probe: gofmt, vet, cross-compile, local run of the parts that need no Linux
if [ -n "$(gofmt -l "$here/probe.go")" ]; then bad "gofmt probe.go"; else ok "gofmt probe.go"; fi
for arch in arm64 amd64; do
  if GOOS=linux GOARCH=$arch go vet "$here/probe.go"; then ok "go vet linux/$arch"; else bad "go vet linux/$arch"; fi
done
if GOOS=linux GOARCH=arm64 CGO_ENABLED=0 go build -trimpath -o "$tmp/probe-arm64" "$here/probe.go"; then ok "cross-compile linux/arm64"; else bad "cross-compile linux/arm64"; fi
mkdir -p "$tmp/host"
awk '
  /^\/\/go:build linux$/ { next }
  /^\/\/ BEGIN LINUX-ONLY$/ { skip = 1; next }
  /^\/\/ END LINUX-ONLY$/ { skip = 0; next }
  !skip { print }' "$here/probe.go" >"$tmp/host/probe.go"
cat >>"$tmp/host/probe.go" <<'GO'

// Stubs for the local run on a machine that is not Linux (generated by check-kit.sh).
var _ unsafe.Pointer

func clockGettime(id uintptr) (time.Duration, error) { return 0, errors.New("stub") }

func peerCred(c *net.UnixConn) (uid, gid, pid int, err error) { return 0, 0, 0, errors.New("stub") }
GO
if (cd "$tmp/host" && go build -o "$tmp/probe-host" probe.go) && "$tmp/probe-host" selftest | tee "$tmp/selftest.out" | grep -q '^selftest ok$'; then
  ok "local selftest (pure parts, Linux calls stubbed)"
else bad "local selftest"; cat "$tmp/selftest.out" 2>/dev/null; fi

# 3. the sandbox fragments are verbatim copies
awk '/^  User=root$/ { on = 1 } on { ln = $0; sub(/^  /, "", ln); print ln } /^  Nice=10$/ { exit }' "$repo/docs/adr/0010-update-helper.md" |
  sed -e 's#^ReadWritePaths=/opt/oarfish$#ReadWritePaths=/opt/oarfish-spike#' -e 's#^StateDirectory=oarfish-update$#StateDirectory=oarfish-spike-update#' >"$tmp/helper.expect"
if cmp -s "$tmp/helper.expect" "$here/fragments/helper-sandbox.inc" && [ -s "$tmp/helper.expect" ]; then ok "helper-sandbox.inc equals the U10 text of ADR 0010 (two spike substitutions)"; else bad "helper-sandbox.inc differs from ADR 0010 U10"; fi
{ echo "UMask=0077"; awk '/^NoNewPrivileges=yes$/ { on = 1 } on { print } /^SystemCallErrorNumber=EPERM$/ { exit }' "$repo/install/oarfish.service"; } >"$tmp/service.expect"
if cmp -s "$tmp/service.expect" "$here/fragments/service-sandbox.inc" && [ -s "$tmp/service.expect" ]; then ok "service-sandbox.inc equals the hardening block of install/oarfish.service"; else bad "service-sandbox.inc differs from install/oarfish.service"; fi
# the other lines of the U10 helper unit appear in the V11 unit, with spike names and one value change
for line in 'OnFailure=oarfish-spike-recover.service' 'StartLimitIntervalSec=10' 'StartLimitBurst=3' 'Type=exec' 'Restart=on-failure' 'RestartSec=1' 'RuntimeMaxSec=10'; do
  if grep -qx "$line" "$here/units/oarfish-spike-h11.service"; then ok "h11 unit has $line"; else bad "h11 unit lacks $line"; fi
done
for line in 'OnFailure=oarfish-update-recover.service' 'StartLimitIntervalSec=10' 'StartLimitBurst=3' 'Type=exec' 'Restart=on-failure' 'RestartSec=1' 'RuntimeMaxSec=900'; do
  if grep -qx "  $line" "$repo/docs/adr/0010-update-helper.md"; then ok "ADR U10 has $line"; else bad "ADR U10 lacks $line"; fi
done
for line in 'Type=simple' 'Restart=on-failure' 'RestartSec=2' 'TimeoutStopSec=15'; do
  if grep -qx "$line" "$repo/install/oarfish.service" && grep -qx "$line" "$here/units/oarfish-spike-crashloop.service"; then ok "crashloop unit mirrors $line of oarfish.service"; else bad "crashloop unit differs on $line"; fi
done

# 4. assemble every unit and check the safety rules
OARFISH_SPIKE_SOURCE_ONLY=1
export OARFISH_SPIKE_SOURCE_ONLY
KIT="$here"
# shellcheck source=spike.sh
. "$here/spike.sh"
mkdir -p "$tmp/units"
for t in "$here"/units/*.service "$here"/units/*.socket; do assemble_unit "$t" "$tmp/units/$(basename "$t")"; done
n=$(find "$tmp/units" -type f | wc -l | tr -d ' ')
ok "assembled $n unit files"
if grep -l '@@' "$tmp"/units/* >/dev/null 2>&1; then bad "an unreplaced marker is left"; else ok "no marker left"; fi
for u in "$tmp"/units/* "$here"/units/v10/R*/*; do
  b=$(basename "$u")
  case $b in oarfish-spike-*) ;; *) bad "unit name without prefix: $b" ;; esac
done
ok "all unit names carry the prefix"
if grep -nE '^(Requires|Wants|BindsTo|PartOf|After|Before|Conflicts|Upholds|RequiredBy|WantedBy|OnFailure|OnSuccess)=' "$tmp"/units/* "$here"/units/v10/R*/* |
  grep -vE '=(oarfish-spike-[a-z0-9.-]+(\.service|\.socket)?|multi-user\.target)$'; then bad "a unit names something that is not a spike unit or multi-user.target"; else ok "no dependency or ordering on anything but spike units"; fi
if grep -nE 'oarfish\.service|/opt/oarfish([^-]|$)|/etc/oarfish|/var/lib/oarfish([^-]|$)|/var/cache/oarfish([^-]|$)|/run/oarfish([^-]|$)' "$here"/units/* "$here"/units/v10/R*/* 2>/dev/null | grep -v '^[^:]*:[0-9]*:#'; then bad "a unit mentions a production path or unit outside a comment"; else ok "no unit mentions a production path or unit"; fi
for u in "$here"/units/*.service "$here"/units/v10/R*/*.service; do
  v=$(sed -n 's/^TimeoutStartSec=//p' "$u")
  case $v in '' | *[!0-9]*) bad "$(basename "$u"): no numeric TimeoutStartSec" ;; *) if [ "$v" -le 30 ]; then :; else bad "$(basename "$u"): TimeoutStartSec above 30"; fi ;; esac
done
ok "every service unit has TimeoutStartSec of at most 30"
if grep -l '^WantedBy=' "$here"/units/*.service "$here"/units/v10/R*/*.service | sed 's#.*/##' | sort -u | tr '\n' ' ' | grep -qE '^oarfish-spike-v10a\.service oarfish-spike-v10b\.service oarfish-spike-v10c\.service oarfish-spike-v10d\.service oarfish-spike-v8-boot\.service $'; then ok "only v8-boot and v10a to v10d are installable (enabled for the reboot)"; else bad "unexpected [Install] sections"; fi

# 5. production names in the scripts only in read-only commands
bad_lines=$(grep -nE 'oarfish\.service|/opt/oarfish([^-]|$)|/etc/oarfish|/var/lib/oarfish([^-]|$)|/var/cache/oarfish([^-]|$)|/run/oarfish([^-]|$)' "$here/spike.sh" "$here/probe.go" |
  grep -vE '^[^:]*:[0-9]+:[[:space:]]*#' |
  grep -E '(systemctl[[:space:]]+(start|stop|restart|enable|disable|reset-failed|link|reload)|[[:space:]](rm|cp|mv|ln|chmod|chown|mkdir|tee|touch|install)[[:space:]]|>[[:space:]]*/|OpenFile|WriteFile|Remove|Rename|Symlink)' || true)
if [ -n "$bad_lines" ]; then bad "a production name appears in a mutating command:"; printf '%s\n' "$bad_lines"; else ok "production names appear only in read-only commands"; fi
printf '      lines that mention production names (for review):\n'
grep -nE 'oarfish\.service|/opt/oarfish([^-]|$)|/etc/oarfish|/var/lib/oarfish([^-]|$)|/var/cache/oarfish([^-]|$)|/run/oarfish([^-]|$)' "$here/spike.sh" "$here/probe.go" | grep -vE '^[^:]*:[0-9]+:[[:space:]]*#' | sed 's/^/      /'

# 6. forbidden identifiers in the whole kit
ip=$(grep -rnE '([0-9]{1,3}\.){3}[0-9]{1,3}' "$here" --exclude-dir=build --exclude=check-kit.sh | grep -vE '127\.0\.0\.1|127\.0\.0\.0..8|0\.0\.0\.0..0' || true)
if [ -n "$ip" ]; then bad "IPv4 literal in the kit:"; printf '%s\n' "$ip"; else ok "no IPv4 literal other than loopback and 0.0.0.0/0"; fi
mac=$(grep -rnEi '([0-9a-f]{2}:){5}[0-9a-f]{2}' "$here" --exclude-dir=build || true)
if [ -n "$mac" ]; then bad "MAC-like literal in the kit:"; printf '%s\n' "$mac"; else ok "no MAC address literal"; fi
v6=$(grep -rnE '([0-9a-fA-F]{1,4}:){2,7}[0-9a-fA-F]{1,4}' "$here" --exclude-dir=build --exclude=check-kit.sh | grep -vE '[0-9]{2}:[0-9]{2}:[0-9]{2}' || true)
if [ -n "$v6" ]; then bad "IPv6-like literal in the kit:"; printf '%s\n' "$v6"; else ok "no IPv6 literal"; fi
who=$(grep -rnE '/Users/|/home/[a-z]|raspberrypi|\.local\b|[A-Za-z0-9._-]+@[A-Za-z0-9._-]+' "$here" --exclude-dir=build --exclude=check-kit.sh | grep -vE 'USER@DEVICE|@P[0-9]@' || true)
if [ -n "$who" ]; then bad "possible host or user identifier:"; printf '%s\n' "$who"; else ok "no host name, user name or home path (USER@DEVICE is the only placeholder)"; fi
if [ -n "$(find "$here" -type f \( -name '*.bin' -o -name 'oarfish-spike-probe' \) -not -path '*/build/*')" ]; then bad "a binary outside build/"; else ok "no binary outside the ignored build/ directory"; fi
if git -C "$repo" check-ignore -q "docs/spikes/g6-1/build/oarfish-spike-probe"; then ok "build/ is ignored by git"; else bad "build/ is not ignored by git"; fi

# 7. the committed checksum belongs to the current source
if [ -f "$here/build/oarfish-spike-probe" ]; then
  want=$(awk '{print $1; exit}' "$here/probe.sha256")
  if command -v sha256sum >/dev/null 2>&1; then have=$(sha256sum "$here/build/oarfish-spike-probe" | awk '{print $1}'); else have=$(shasum -a 256 "$here/build/oarfish-spike-probe" | awk '{print $1}'); fi
  if [ "$want" = "$have" ]; then ok "probe.sha256 matches build/oarfish-spike-probe"; else bad "probe.sha256 does not match the built probe: run build-probe.sh"; fi
else skip "no build/ directory: run build-probe.sh"; fi

# 8. the runbook names the checksum of the current build
want=$(awk '{print $1; exit}' "$here/probe.sha256")
if grep -q "sha256: $want" "$here/README.md"; then ok "README.md names the checksum of probe.sha256"; else bad "README.md does not name the checksum of probe.sha256"; fi

if [ "$fails" -eq 0 ]; then echo "all checks passed"; else echo "$fails check(s) failed"; exit 1; fi
